CREATE TABLE app.parameters (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id          uuid NOT NULL,
  plant_id           uuid NOT NULL,
  code               text NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9_]{1,40}$'),
  name               text NOT NULL,
  short_name         text,
  group_key          text NOT NULL CHECK (group_key IN ('key','chemical','lab_inlet','lab_outlet','safety','staff','cash','other')),
  unit               text NOT NULL,
  input_mode         text NOT NULL CHECK (input_mode IN ('typed','calculated','suggested')),
  formula            text,
  decimals           int NOT NULL DEFAULT 2 CHECK (decimals BETWEEN 0 AND 6),
  hard_min           numeric(18,6),
  hard_max           numeric(18,6),
  aggregation        text NOT NULL CHECK (aggregation IN ('sum','avg','snapshot','stock','text')),
  std_type           text NOT NULL CHECK (std_type IN ('per_day','monthly_allowance','range','required_qty','none')),
  direction          text NOT NULL CHECK (direction IN ('higher_better','lower_better','within_range','neutral')),
  event_rule         text NOT NULL CHECK (event_rule IN ('above_std','below_std','outside_range','none')),
  result_noun        text,
  link_role          text CHECK (link_role IN ('consumed','received','balance','vacant','present','leave','absent',
                                               'available','expense','cash_received','cash_balance','description')),
  stock_item_id      uuid,
  staff_category_id  uuid,
  safety_item_id     uuid,
  logsheet_block     int,
  logsheet_order     int,
  mis_section        text,
  mis_order          int,
  dashboard_card     boolean NOT NULL DEFAULT false,
  dashboard_order    int,
  chart_type         text NOT NULL DEFAULT 'none' CHECK (chart_type IN ('bar','line','cone','none')),
  chart_metric       text CHECK (chart_metric IN ('avg_per_day','monthly_total')),
  mandatory          boolean NOT NULL DEFAULT true,
  active_from        date,
  active_to          date,
  created_at         timestamptz NOT NULL DEFAULT now(),
  created_by         uuid,
  updated_at         timestamptz,
  updated_by         uuid,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, plant_id, code),
  CHECK (input_mode <> 'calculated' OR formula IS NOT NULL),
  FOREIGN KEY (tenant_id, plant_id)          REFERENCES app.plants (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, stock_item_id)     REFERENCES app.stock_items (tenant_id, id),
  FOREIGN KEY (tenant_id, staff_category_id) REFERENCES app.staff_categories (tenant_id, id),
  FOREIGN KEY (tenant_id, safety_item_id)    REFERENCES app.safety_items (tenant_id, id)
);

